export function buildCrossword({ rows, columns, words }) {
  const cells = Array(rows * columns).fill(null);
  const starts = new Map();

  const clues = words.map(({ answer, clue, row, column, direction }) => {
    const start = row * columns + column;
    const stride = direction === 'down' ? columns : 1;
    if (!starts.has(start)) {
      starts.set(start, starts.size + 1);
    }
    const number = starts.get(start);
    const positions = [...answer].map((letter, offset) => {
      const index = start + offset * stride;
      cells[index] ??= { index, answer: letter };
      return index;
    });

    return { id: `${direction}-${number}`, number, direction, clue, positions };
  });

  for (const [index, number] of starts) {
    cells[index].number = number;
  }

  return { rows, columns, cells, clues };
}

export function checkAnswers(solution, answers) {
  let remaining = 0;
  let incorrect = 0;
  for (const { index, answer } of solution) {
    if (!answers[index]) remaining++;
    else if (answers[index] !== answer) incorrect++;
  }
  return { remaining, incorrect };
}

export function createMemoryDeck(symbols) {
  const deck = [...symbols, ...symbols];
  for (let index = deck.length - 1; index > 0; index--) {
    const other = Math.floor(Math.random() * (index + 1));
    [deck[index], deck[other]] = [deck[other], deck[index]];
  }
  return deck;
}
